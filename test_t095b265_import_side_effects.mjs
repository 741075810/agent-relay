// T265: importing a shipping service module for one of its pure exports must not run that module's CLI.
//
// The defect this pins, reproduced before the fix: `relay_candidate_intake.mjs`, `host_mirror.mjs` and
// `extension_adapter.mjs` decided "was I invoked directly?" with
//   new URL(import.meta.url).pathname.endsWith(process.argv[1].split('/').pop())
// i.e. a *suffix* test on the basename. So any program whose own file name happens to be a suffix of the
// module's name -- `intake.mjs`, `mirror.mjs`, `adapter.mjs` -- triggered `main()` merely by importing it.
// `main()` is not a reader: the intake spawns the real host and then WRITES the candidate store and the
// trigger state; the mirror spawns the host and POSTs to the service; the adapter issues an authenticated
// local HTTP request. A read-only import could therefore mutate the very state a running intake owns.
//
// `relay_service.mjs`, `host_ingest.mjs` and `tools/continuation/bridge_loop_acceptance.mjs` already used the
// exact-path identity test, and `bridge_loop_acceptance.mjs` carries a comment explaining why the suffix test
// was wrong. These three modules now use the same form.
//
// The probe is a separate process on purpose: the module reads `process.argv[1]`, which only a child can be
// given a tricky value for. Every probe lives in a throwaway directory; nothing here touches the repository,
// a running service, the host, or a real store.

import test from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, readdirSync, rmSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));

// `probeName` is chosen so that it is a proper suffix of the module's file name: that is exactly the input the
// suffix test accepted and the exact-path test rejects.
const CASES = [
  { module: 'tools/service/relay_candidate_intake.mjs', export: 'mergeIntoStore', probeName: 'intake.mjs' },
  { module: 'tools/service/host_mirror.mjs', export: 'candidatesFromMirror', probeName: 'mirror.mjs' },
  { module: 'tools/service/extension_adapter.mjs', export: 'admitAll', probeName: 'adapter.mjs' },
];

function withTempDir(run) {
  const dir = mkdtempSync(path.join(os.tmpdir(), 't265-import-'));
  try {
    return run(dir);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

function probeSource(target, exportName) {
  return [
    '// generated by test_t095b265_import_side_effects.mjs',
    `import { ${exportName} } from ${JSON.stringify(target)};`,
    `process.stdout.write(JSON.stringify({ imported: typeof ${exportName}, exitCode: ${'process.exitCode ?? null'} }) + '\\n');`,
    '',
  ].join('\n');
}

for (const { module, export: exportName, probeName } of CASES) {
  test(`T265: importing ${module} from ${probeName} runs no CLI`, () => {
    const target = pathToFileURL(path.join(HERE, module)).href;
    withTempDir((dir) => {
      const probe = path.join(dir, probeName);
      writeFileSync(probe, probeSource(target, exportName), 'utf8');
      const run = spawnSync(process.execPath, [probe], { cwd: dir, encoding: 'utf8', timeout: 60000 });
      assert.equal(run.status, 0, `probe must exit 0, got ${run.status}: ${run.stderr}`);
      assert.equal(run.stderr, '', 'a pure import must write nothing to stderr; main() printing usage is the defect');
      assert.deepEqual(JSON.parse(run.stdout), { imported: 'function', exitCode: null },
        'the process exit code must still be untouched after importing a pure export');
      // Nothing may be created next to the probe: `main()` would have written the store and the trigger state.
      assert.deepEqual(readdirSync(dir), [probeName], 'importing must create no file');
    });
  });
}

for (const { module } of CASES) {
  test(`T265: running ${module} directly still answers with its own usage`, () => {
    const run = spawnSync(process.execPath, [path.join(HERE, module)], {
      cwd: HERE, encoding: 'utf8', timeout: 60000,
    });
    // The exact-path identity test must keep recognising a genuine direct invocation; otherwise the fix would
    // have traded a silent import side effect for a dead CLI.
    assert.equal(run.status, 2, `direct invocation must still refuse with 2, got ${run.status}: ${run.stderr}`);
    assert.match(run.stderr, /usage: /, 'direct invocation must still print its usage line');
  });
}
